#!/usr/bin/env node
// Writes a compressed .webp beside every large PNG/JPEG in public/images and
// regenerates lib/optimizedImages.generated.ts, the list optimizedSrc() reads.
// Originals stay: the database and emails still link to them.
//
//   node client/scripts/optimize-images.mjs          (only new or changed files)
//   node client/scripts/optimize-images.mjs --force  (redo everything)
import { readdirSync, statSync, writeFileSync } from 'node:fs'
import { join, relative } from 'node:path'
import { fileURLToPath } from 'node:url'
import sharp from 'sharp'

const CLIENT = fileURLToPath(new URL('..', import.meta.url))
const PUBLIC = join(CLIENT, 'public')
const ROOT = join(PUBLIC, 'images')
const MIN_BYTES = 60 * 1024 // smaller files are not worth a second copy
const MAX_SIDE = 1200 // covers retina at every size the UI shows
const QUALITY = 78
// SMEEP-only images that ship in public/ but nothing in Hadafi links to.
const SKIP = new Set([
  "/images/smeep-timeline.png",
  "/images/redesign/smeep-avatar-200.png",
  "/images/courses/smeep-course.png",
])
const force = process.argv.includes('--force')

function* walk(dir) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name)
    if (statSync(p).isDirectory()) yield* walk(p)
    else yield p
  }
}

const converted = []
let before = 0
let after = 0
for (const file of walk(ROOT)) {
  if (!/\.(png|jpe?g)$/i.test(file)) continue
  const size = statSync(file).size
  if (size < MIN_BYTES) continue
  const publicPath = '/' + relative(PUBLIC, file).split('\\').join('/')
  if (SKIP.has(publicPath)) continue
  const out = file.replace(/\.(png|jpe?g)$/i, '.webp')
  let fresh = false
  try {
    fresh = !force && statSync(out).mtimeMs >= statSync(file).mtimeMs
  } catch {
    // no .webp yet
  }
  if (!fresh) {
    await sharp(file)
      .resize({ width: MAX_SIDE, height: MAX_SIDE, fit: 'inside', withoutEnlargement: true })
      .webp({ quality: QUALITY, effort: 5 })
      .toFile(out)
  }
  before += size
  after += statSync(out).size
  converted.push(publicPath)
}

converted.sort()
writeFileSync(
  join(CLIENT, 'lib/optimizedImages.generated.ts'),
  `// Generated by scripts/optimize-images.mjs. Do not edit by hand.\n` +
    `// Images under public/ that have a compressed .webp copy beside them.\n` +
    `export const OPTIMIZED_IMAGES: ReadonlySet<string> = new Set(${JSON.stringify(converted, null, 2)})\n`,
)
console.log(`${converted.length} images: ${(before / 1048576).toFixed(1)} MB -> ${(after / 1048576).toFixed(1)} MB as webp`)
